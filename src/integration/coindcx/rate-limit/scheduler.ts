/**
 * M2 W1 shared REST limiter: pure scheduler and protocol state transitions (design V3 §2, §3, §5, §6).
 *
 * Pure: no clock reads, timers, randomness, filesystem, IPC or network. Every transition is
 * `step(state, nowMs, event) -> { state, effects }`, with `nowMs` the coordinator's monotonic time supplied by the
 * caller. Inputs are never mutated. External persistence and evidence are explicit contracts:
 *   - write-ahead persistence: a planned grant is emitted as DELIVER_GRANT only after PERSIST_COMMITTED for a
 *     snapshot revision that contains it (PERSIST effect -> durable write by the caller -> PERSIST_COMMITTED event);
 *   - process-termination evidence is an event the caller may supply only from a justified mechanism (U-M2-9).
 *
 * Budget only: a grant is never execution authority. This module imports no execution or transport code.
 *
 * Pinned limits (not claims):
 *   - Deadline refusal happens when the scheduler is stepped at or after the deadline. Suspension of the
 *     coordinator or client process can delay when a refusal is produced or delivered; no unconditional
 *     real-time bound is claimed.
 *   - Uncertain capacity is released only on positive, trustworthy, irrevocable evidence. A missing or empty
 *     reconnect inventory proves nothing and releases nothing.
 */
import { z } from 'zod';
import { BUDGET_SCOPES, PRIORITY_CLASSES, type BudgetScope, type PriorityClass, type RateLimiterConfig } from './config';
import { fullRetainedWaitMs, serverWaitBound, type RetryAfterContext } from './retry-after';

export type BudgetOperation = 'READ' | 'PROBE' | 'CREATE' | 'CANCEL';
export type ReportKind = 'RECEIVED' | 'STARTED' | 'NOT_STARTED' | 'COMPLETED';
export type UnknownReason = 'SNAPSHOT_UNREADABLE' | 'CLOCK_REGRESSION' | 'PERSISTENCE_FAILED' | 'RETRY_AFTER_UNBOUNDED';
export type RefusalCode = 'DEADLINE' | 'INVALID_REQUEST' | 'INVALID_DEADLINE' | 'DUPLICATE_ID' | 'SESSION_INVALID' | 'SESSION_CLOSED'
  | 'HOOK_TOKEN_MISMATCH' | 'ADMISSION_STOPPED' | 'STALE_PROBE' | 'STATE_UNKNOWN';
export type AlertCode = 'UNCERTAIN_CHARGE_OUTSTANDING' | 'SLOT_OVERDUE' | 'WAIT_EXCEEDS_OPERATIONAL_CAP' | 'RETRY_AFTER_OVERFLOW'
  | 'RETRY_AFTER_PRESENT_BUT_UNPARSEABLE' | 'DATE_CONVERSION_UNCERTAIN' | 'PROTOCOL_VIOLATION' | 'REPORT_FROM_OTHER_CLIENT'
  | 'INVENTORY_CONTRADICTION' | 'STALE_PROBE_RESULT' | 'RESET_REFUSED_STATE_UNKNOWN' | 'UNKNOWN_PERSIST_REVISION'
  | 'CLOCK_REGRESSION' | 'PERSISTENCE_FAILED' | 'SESSION_EVENT_INVALID';

export interface BudgetRequest {
  readonly requestId: string;
  /** Unguessable id generated by the coordinator shell (W2); the grant's report capability. */
  readonly grantId: string;
  readonly clientInstanceId: string;
  readonly sessionId: string;
  readonly cls: PriorityClass;
  readonly operation: BudgetOperation;
  readonly scope: BudgetScope;
  /** Absolute coordinator time; finite and within the configured cap. */
  readonly deadlineMs: number;
  /** Expected request lifetime (primitive envelope). Used only for the overdue alert. */
  readonly lifetimeMs: number;
  /** PROBE only: the probe generation announced by PROBE_DUE. */
  readonly probeGen?: number;
  /** CANCEL only: the token registered by the cancellation hook (M6). Budget eligibility only. */
  readonly hookToken?: object;
}
export interface Grant {
  readonly epoch: string; readonly sessionId: string; readonly grantId: string; readonly requestId: string;
  readonly ttlMs: number; readonly operation: BudgetOperation; readonly scope: BudgetScope;
  readonly viaHook: boolean; readonly probeGen: number | null;
}
export type SchedulerEvent =
  | Readonly<{ type: 'ADVANCE' }>
  | Readonly<{ type: 'SESSION_OPENED'; sessionId: string; clientInstanceId: string }>
  | Readonly<{ type: 'SESSION_CLOSED'; sessionId: string }>
  | Readonly<{ type: 'ENQUEUE'; request: BudgetRequest }>
  | Readonly<{ type: 'REPORT'; clientInstanceId: string; grantId: string; kind: ReportKind }>
  /** Explicit per-grant statements only. Grants not listed are untouched. */
  | Readonly<{ type: 'INVENTORY'; clientInstanceId: string; used: readonly string[]; voided: readonly string[] }>
  /** Justified termination evidence from an approved mechanism (U-M2-9). Pipe disconnect is NOT this event. */
  | Readonly<{ type: 'TERMINATION_EVIDENCE'; clientInstanceId: string; evidence: 'OS_PROCESS_EXIT' | 'HOST_BOOT_CHANGED' }>
  | Readonly<{ type: 'THROTTLE_OBSERVED'; retryAfter: RetryAfterContext }>
  | Readonly<{ type: 'PROBE_RESULT'; scope: BudgetScope; probeGen: number; outcome: 'SUCCESS' | 'FAILED' }>
  | Readonly<{ type: 'STOP' }>
  | Readonly<{ type: 'RESET_STOP' }>
  | Readonly<{ type: 'HOOK_REGISTERED'; token: object }>
  | Readonly<{ type: 'PERSIST_COMMITTED'; revision: number }>
  | Readonly<{ type: 'PERSIST_FAILED'; revision: number }>;
export type SchedulerEffect =
  | Readonly<{ kind: 'PERSIST'; revision: number; snapshot: LimiterSnapshot }>
  | Readonly<{ kind: 'DELIVER_GRANT'; grant: Grant }>
  | Readonly<{ kind: 'REFUSE'; requestId: string; sessionId: string; code: RefusalCode }>
  | Readonly<{ kind: 'REVOKE'; sessionId: string; grantIds: readonly string[] }>
  | Readonly<{ kind: 'PROBE_DUE'; scope: BudgetScope; probeGen: number }>
  | Readonly<{ kind: 'REPORT_IGNORED'; grantId: string; reason: 'UNKNOWN_GRANT' | 'OTHER_CLIENT' | 'NOT_DELIVERED' | 'DUPLICATE' | 'AFTER_STARTED' }>
  | Readonly<{ kind: 'ALERT'; code: AlertCode; detail: string }>;

export type ScopeThrottle = Readonly<{ kind: 'CLEAR' }> | Readonly<{ kind: 'BLOCKED'; notBeforeMs: number }> | Readonly<{ kind: 'PROBING'; probeGen: number; probeGranted: boolean }>;
export interface BlockRecord { readonly receivedAtMs: number; readonly fullWaitMs: number; readonly form: string }
export interface ChargeRecord {
  readonly grantId: string; readonly requestId: string; readonly clientInstanceId: string; readonly sessionId: string; readonly epoch: string;
  readonly cls: PriorityClass; readonly operation: BudgetOperation; readonly scope: BudgetScope; readonly viaHook: boolean; readonly probeGen: number | null;
  readonly lifetimeMs: number; readonly grantedAtMs: number;
  /** Latest possible start on this incarnation's monotonic clock; null = unresolved (infinite). */
  readonly latestStartMs: number | null;
  readonly started: boolean; readonly slotHeld: boolean;
  readonly delivery: 'PENDING_PERSIST' | 'DELIVERED'; readonly persistRevision: number;
  readonly uncertainAlerted: boolean; readonly overdueAlerted: boolean; readonly seen: readonly ReportKind[];
}
interface QueuedRequest {
  readonly request: BudgetRequest; readonly viaHook: boolean;
}
interface SessionRecord { readonly clientInstanceId: string; readonly open: boolean }
export interface LimiterState {
  readonly config: RateLimiterConfig;
  readonly epoch: string;
  readonly lastNowMs: number;
  readonly admission: 'OPEN' | 'STOPPED';
  readonly unknown: UnknownReason | null;
  readonly scopes: Readonly<Record<BudgetScope, ScopeThrottle>>;
  readonly failuresInRow: number;
  readonly blocks: readonly BlockRecord[];
  readonly probeGenCounter: number;
  readonly charges: readonly ChargeRecord[];
  readonly queue: readonly QueuedRequest[];
  readonly sessions: Readonly<Record<string, SessionRecord>>;
  readonly revision: number;
  readonly committedRevision: number;
  /** Not persisted: identity of the registered cancellation-hook token. Absent after every restore. */
  readonly hookToken: object | null;
}
export interface StepResult { readonly state: LimiterState; readonly effects: readonly SchedulerEffect[] }

type Draft = Omit<{ -readonly [K in keyof LimiterState]: LimiterState[K] }, 'charges' | 'queue' | 'sessions' | 'scopes' | 'blocks'>
  & { charges: ChargeRecord[]; queue: QueuedRequest[]; sessions: Record<string, SessionRecord>; scopes: Record<BudgetScope, ScopeThrottle>; blocks: BlockRecord[] };
interface Ctx { s: Draft; now: number; effects: SchedulerEffect[]; dirty: boolean }

const ID = /^[A-Za-z0-9._:-]{1,128}$/;
const isId = (value: unknown): value is string => typeof value === 'string' && ID.test(value);
const isTime = (value: unknown): value is number => Number.isSafeInteger(value) && (value as number) >= 0;
const isMutation = (operation: BudgetOperation): boolean => operation === 'CREATE' || operation === 'CANCEL';

/** Fresh state: only when no prior coordinator run exists. After any prior run use `restoreLimiterState`. */
export function createLimiterState(config: RateLimiterConfig, nowMs: number, epoch: string): LimiterState {
  if (!isTime(nowMs) || !isId(epoch)) throw new TypeError('createLimiterState: invalid nowMs or epoch');
  return Object.freeze({
    config, epoch, lastNowMs: nowMs, admission: 'OPEN', unknown: null,
    scopes: Object.freeze({ API_AUTH: { kind: 'CLEAR' } as const, PUBLIC: { kind: 'CLEAR' } as const }), failuresInRow: 0, blocks: [], probeGenCounter: 0,
    charges: [], queue: [], sessions: {}, revision: 0, committedRevision: 0, hookToken: null,
  });
}

function draft(state: LimiterState): Draft {
  return {
    ...state, scopes: { ...state.scopes }, blocks: [...state.blocks], charges: state.charges.map((charge) => ({ ...charge })),
    queue: [...state.queue], sessions: { ...state.sessions },
  };
}
const setCharge = (ctx: Ctx, index: number, patch: Partial<ChargeRecord>): void => { ctx.s.charges[index] = { ...ctx.s.charges[index]!, ...patch }; };
const alert = (ctx: Ctx, code: AlertCode, detail: string): void => { ctx.effects.push(Object.freeze({ kind: 'ALERT', code, detail })); };
const refuse = (ctx: Ctx, request: BudgetRequest, code: RefusalCode): void => {
  ctx.effects.push(Object.freeze({ kind: 'REFUSE', requestId: request.requestId, sessionId: request.sessionId, code }));
};
const allClear = (s: Draft | LimiterState): boolean => BUDGET_SCOPES.every((scope) => s.scopes[scope].kind === 'CLEAR');
const active = (s: Draft, now: number, windowMs: number, cls?: PriorityClass): number =>
  s.charges.filter((charge) => (cls === undefined || charge.cls === cls) && (charge.latestStartMs === null || charge.latestStartMs + windowMs > now)).length;

export function step(state: LimiterState, nowMs: number, event: SchedulerEvent): StepResult {
  const ctx: Ctx = { s: draft(state), now: nowMs, effects: [], dirty: false };
  if (!isTime(nowMs) || nowMs < state.lastNowMs) {
    // A monotonic clock cannot move backwards: fail closed.
    ctx.now = state.lastNowMs;
    enterUnknown(ctx, 'CLOCK_REGRESSION');
    alert(ctx, 'CLOCK_REGRESSION', `now ${String(nowMs)} < last ${state.lastNowMs}`);
    progress(ctx);
    return finish(ctx);
  }
  ctx.s.lastNowMs = nowMs;
  apply(ctx, event);
  progress(ctx);
  return finish(ctx);
}

function finish(ctx: Ctx): StepResult {
  if (ctx.dirty && ctx.s.unknown !== 'PERSISTENCE_FAILED') {
    ctx.s.revision += 1;
    ctx.s.charges = ctx.s.charges.map((charge) => (charge.delivery === 'PENDING_PERSIST' && charge.persistRevision === -1 ? { ...charge, persistRevision: ctx.s.revision } : charge));
    ctx.effects.push(Object.freeze({ kind: 'PERSIST', revision: ctx.s.revision, snapshot: snapshotOf(ctx.s, ctx.now) }));
  }
  const state: LimiterState = Object.freeze({ ...ctx.s, scopes: Object.freeze(ctx.s.scopes), blocks: Object.freeze(ctx.s.blocks), charges: Object.freeze(ctx.s.charges), queue: Object.freeze(ctx.s.queue), sessions: Object.freeze(ctx.s.sessions) });
  return Object.freeze({ state, effects: Object.freeze(ctx.effects) });
}

function enterUnknown(ctx: Ctx, reason: UnknownReason): void {
  const next = ctx.s.unknown === null || reason === 'PERSISTENCE_FAILED' ? reason : ctx.s.unknown;
  if (next !== ctx.s.unknown) { ctx.s.unknown = next; ctx.dirty = true; } // persist only a change; repeated regressions do not re-persist
}

function apply(ctx: Ctx, event: SchedulerEvent): void {
  const s = ctx.s;
  switch (event.type) {
    case 'ADVANCE': return;
    case 'SESSION_OPENED':
      if (!isId(event.sessionId) || !isId(event.clientInstanceId) || s.sessions[event.sessionId] !== undefined) { alert(ctx, 'SESSION_EVENT_INVALID', 'open'); return; }
      s.sessions[event.sessionId] = { clientInstanceId: event.clientInstanceId, open: true };
      return;
    case 'SESSION_CLOSED': {
      const session = s.sessions[event.sessionId];
      if (session === undefined) { alert(ctx, 'SESSION_EVENT_INVALID', 'close'); return; }
      // Closing a session releases nothing: grants that passed the client check may still start (design V3 §2.4).
      s.sessions[event.sessionId] = { ...session, open: false };
      s.queue = s.queue.filter((queued) => { if (queued.request.sessionId !== event.sessionId) return true; refuse(ctx, queued.request, 'SESSION_CLOSED'); return false; });
      return;
    }
    case 'ENQUEUE': enqueue(ctx, event.request); return;
    case 'REPORT': report(ctx, event.clientInstanceId, event.grantId, event.kind); return;
    case 'INVENTORY': {
      const used = new Set(event.used), voided = new Set(event.voided);
      for (const id of used) if (voided.has(id)) alert(ctx, 'INVENTORY_CONTRADICTION', id);
      for (const id of used) if (!voided.has(id)) report(ctx, event.clientInstanceId, id, 'STARTED');
      for (const id of voided) if (!used.has(id)) report(ctx, event.clientInstanceId, id, 'NOT_STARTED');
      return;
    }
    case 'TERMINATION_EVIDENCE':
      s.charges.forEach((charge, index) => {
        if (charge.clientInstanceId !== event.clientInstanceId) return;
        // A terminated process starts nothing later: bound D by now (charge stays until now + W). Sockets are torn down.
        setCharge(ctx, index, { latestStartMs: charge.latestStartMs === null ? ctx.now : Math.min(charge.latestStartMs, ctx.now), slotHeld: false });
        ctx.dirty = true;
      });
      for (const [id, session] of Object.entries(s.sessions)) if (session.clientInstanceId === event.clientInstanceId && session.open) apply(ctx, { type: 'SESSION_CLOSED', sessionId: id });
      return;
    case 'THROTTLE_OBSERVED': throttleObserved(ctx, event.retryAfter); return;
    case 'PROBE_RESULT': {
      const current = s.scopes[event.scope];
      if (current === undefined || current.kind !== 'PROBING' || current.probeGen !== event.probeGen) { alert(ctx, 'STALE_PROBE_RESULT', `${String(event.scope)}#${String(event.probeGen)}`); return; }
      if (event.outcome === 'SUCCESS') {
        // A probe changes only the throttle of its own scope; it never touches the admission latch.
        s.scopes[event.scope] = { kind: 'CLEAR' };
        if (allClear(s)) { s.failuresInRow = 0; s.blocks = []; }
      } else {
        const backoff = Math.min(s.config.retryAfter.localBackoffBaseMs * 2 ** Math.min(s.failuresInRow, 52), s.config.retryAfter.localBackoffMaxMs);
        s.failuresInRow += 1;
        s.blocks.push({ receivedAtMs: ctx.now, fullWaitMs: backoff, form: 'LOCAL_BACKOFF' });
        s.scopes[event.scope] = { kind: 'BLOCKED', notBeforeMs: ctx.now + backoff };
      }
      ctx.dirty = true;
      return;
    }
    case 'STOP':
      s.admission = 'STOPPED'; ctx.dirty = true;
      revoke(ctx, (charge) => isMutation(charge.operation) && !charge.viaHook);
      return;
    case 'RESET_STOP':
      if (s.unknown !== null) { alert(ctx, 'RESET_REFUSED_STATE_UNKNOWN', s.unknown); return; }
      s.admission = 'OPEN'; ctx.dirty = true; // the throttle is untouched
      return;
    case 'HOOK_REGISTERED': s.hookToken = event.token; return;
    case 'PERSIST_COMMITTED': {
      if (!Number.isSafeInteger(event.revision) || event.revision > s.revision) { alert(ctx, 'UNKNOWN_PERSIST_REVISION', String(event.revision)); return; }
      s.committedRevision = Math.max(s.committedRevision, event.revision);
      if (s.unknown === 'PERSISTENCE_FAILED') return;
      const keep: ChargeRecord[] = [];
      for (const charge of s.charges) {
        if (charge.delivery !== 'PENDING_PERSIST' || charge.persistRevision > s.committedRevision) { keep.push(charge); continue; }
        // Re-check at delivery: a block, stop, unknown state or closed session since planning voids the grant.
        // It was never sent, so the coordinator's own decision is positive evidence of non-use.
        if (s.sessions[charge.sessionId]?.open !== true || !deliverable(s, charge)) { ctx.dirty = true; continue; }
        keep.push({ ...charge, delivery: 'DELIVERED' });
        ctx.effects.push(Object.freeze({ kind: 'DELIVER_GRANT', grant: Object.freeze({
          epoch: charge.epoch, sessionId: charge.sessionId, grantId: charge.grantId, requestId: charge.requestId, ttlMs: s.config.grantTtlMs,
          operation: charge.operation, scope: charge.scope, viaHook: charge.viaHook, probeGen: charge.probeGen,
        }) }));
      }
      s.charges = keep;
      return;
    }
    case 'PERSIST_FAILED':
      // Durability unknown: fail closed. Undelivered grants were never sent and are voided by the coordinator itself.
      s.charges = s.charges.filter((charge) => charge.delivery !== 'PENDING_PERSIST');
      enterUnknown(ctx, 'PERSISTENCE_FAILED');
      alert(ctx, 'PERSISTENCE_FAILED', String(event.revision));
      return;
  }
}

function enqueue(ctx: Ctx, request: BudgetRequest): void {
  const s = ctx.s, config = s.config;
  const valid = isId(request.requestId) && isId(request.grantId) && isId(request.clientInstanceId) && isId(request.sessionId)
    && (PRIORITY_CLASSES as readonly string[]).includes(request.cls) && (BUDGET_SCOPES as readonly string[]).includes(request.scope)
    && ['READ', 'PROBE', 'CREATE', 'CANCEL'].includes(request.operation)
    && Number.isSafeInteger(request.lifetimeMs) && request.lifetimeMs > 0
    && (!isMutation(request.operation) || request.scope === 'API_AUTH')
    && (request.operation === 'PROBE' ? Number.isSafeInteger(request.probeGen) : request.probeGen === undefined)
    && (request.hookToken === undefined || request.operation === 'CANCEL');
  if (!valid) { refuse(ctx, request, 'INVALID_REQUEST'); return; }
  if (s.charges.some((charge) => charge.grantId === request.grantId) || s.queue.some((queued) => queued.request.grantId === request.grantId || queued.request.requestId === request.requestId)) { refuse(ctx, request, 'DUPLICATE_ID'); return; }
  const session = s.sessions[request.sessionId];
  if (session === undefined || !session.open || session.clientInstanceId !== request.clientInstanceId) { refuse(ctx, request, 'SESSION_INVALID'); return; }
  if (!Number.isSafeInteger(request.deadlineMs) || request.deadlineMs <= ctx.now || request.deadlineMs > ctx.now + config.maxRequestDeadlineMs) { refuse(ctx, request, 'INVALID_DEADLINE'); return; }
  let viaHook = false;
  if (request.hookToken !== undefined) {
    if (s.hookToken === null || request.hookToken !== s.hookToken) { refuse(ctx, request, 'HOOK_TOKEN_MISMATCH'); return; }
    viaHook = true;
  }
  s.queue.push(Object.freeze({ request: Object.freeze({ ...request }), viaHook }));
}

function report(ctx: Ctx, clientInstanceId: string, grantId: string, kind: ReportKind): void {
  const s = ctx.s;
  const index = s.charges.findIndex((charge) => charge.grantId === grantId);
  const ignored = (reason: 'UNKNOWN_GRANT' | 'OTHER_CLIENT' | 'NOT_DELIVERED' | 'DUPLICATE' | 'AFTER_STARTED'): void => { ctx.effects.push(Object.freeze({ kind: 'REPORT_IGNORED', grantId, reason })); };
  if (index < 0) { ignored('UNKNOWN_GRANT'); return; }
  const charge = s.charges[index]!;
  // The grantId is the capability and the report must come from the client instance it was issued to; epoch and session do not matter.
  if (charge.clientInstanceId !== clientInstanceId) { alert(ctx, 'REPORT_FROM_OTHER_CLIENT', grantId); ignored('OTHER_CLIENT'); return; }
  if (charge.delivery !== 'DELIVERED') { alert(ctx, 'PROTOCOL_VIOLATION', `report before delivery ${grantId}`); ignored('NOT_DELIVERED'); return; }
  if (charge.seen.includes(kind)) { ignored('DUPLICATE'); return; }
  const seen = [...charge.seen, kind];
  const startBound = charge.latestStartMs === null ? ctx.now : Math.min(charge.latestStartMs, ctx.now);
  switch (kind) {
    case 'RECEIVED': setCharge(ctx, index, { seen }); return; // no accounting effect (design V3 §2.2)
    case 'STARTED': setCharge(ctx, index, { seen, started: true, latestStartMs: startBound }); ctx.dirty = true; return;
    case 'COMPLETED': setCharge(ctx, index, { seen, started: true, latestStartMs: startBound, slotHeld: false }); ctx.dirty = true; return;
    case 'NOT_STARTED':
      if (charge.started) { alert(ctx, 'PROTOCOL_VIOLATION', `NOT_STARTED after STARTED ${grantId}`); ignored('AFTER_STARTED'); return; }
      s.charges.splice(index, 1); // irrevocable void of an unused grant: the only refund
      ctx.dirty = true;
      return;
  }
}

function throttleObserved(ctx: Ctx, context: RetryAfterContext): void {
  const s = ctx.s, policy = s.config.retryAfter;
  const bound = serverWaitBound(context, policy);
  const fullWaitMs = fullRetainedWaitMs(bound, s.failuresInRow, policy);
  s.failuresInRow += 1;
  ctx.dirty = true;
  revoke(ctx, () => true);
  if (bound.kind === 'UNBOUNDED' || !Number.isFinite(fullWaitMs)) {
    alert(ctx, bound.kind === 'UNBOUNDED' ? bound.alert : 'RETRY_AFTER_OVERFLOW', 'fail closed until an operator decision (U-M2-5)');
    enterUnknown(ctx, 'RETRY_AFTER_UNBOUNDED');
    return;
  }
  if (fullWaitMs > policy.operationalCapMs) alert(ctx, 'WAIT_EXCEEDS_OPERATIONAL_CAP', String(fullWaitMs));
  s.blocks.push({ receivedAtMs: ctx.now, fullWaitMs, form: bound.kind === 'DEFAULT' ? 'NO_HEADER_DEFAULT' : bound.form });
  // The provider block is per IP (shared): every scope is blocked and needs its own successful probe.
  for (const scope of BUDGET_SCOPES) {
    const current = s.scopes[scope];
    const existing = current.kind === 'BLOCKED' ? current.notBeforeMs : 0;
    s.scopes[scope] = { kind: 'BLOCKED', notBeforeMs: Math.max(existing, ctx.now + fullWaitMs) };
  }
}

/** Ask holders of delivered, not-yet-started grants to void them. Charges stay until NOT_STARTED arrives. */
function revoke(ctx: Ctx, predicate: (charge: ChargeRecord) => boolean): void {
  const bySession = new Map<string, string[]>();
  for (const charge of ctx.s.charges) {
    if (charge.delivery !== 'DELIVERED' || charge.started || !predicate(charge) || ctx.s.sessions[charge.sessionId]?.open !== true) continue;
    bySession.set(charge.sessionId, [...(bySession.get(charge.sessionId) ?? []), charge.grantId]);
  }
  for (const [sessionId, grantIds] of bySession) ctx.effects.push(Object.freeze({ kind: 'REVOKE', sessionId, grantIds: Object.freeze(grantIds) }));
}

function eligible(s: Draft, queued: QueuedRequest): boolean {
  const { request } = queued;
  if (request.operation === 'PROBE') {
    const scope = s.scopes[request.scope];
    return scope.kind === 'PROBING' && scope.probeGen === request.probeGen && !scope.probeGranted;
  }
  if (request.operation === 'READ') return s.scopes[request.scope].kind === 'CLEAR';
  return allClear(s) && (s.admission === 'OPEN' || (queued.viaHook && s.hookToken !== null));
}
function deliverable(s: Draft, charge: ChargeRecord): boolean {
  if (s.unknown !== null) return false;
  if (charge.operation === 'PROBE') { const scope = s.scopes[charge.scope]; return scope.kind === 'PROBING' && scope.probeGen === charge.probeGen; }
  if (charge.operation === 'READ') return s.scopes[charge.scope].kind === 'CLEAR';
  return allClear(s) && (s.admission === 'OPEN' || (charge.viaHook && s.hookToken !== null));
}

function progress(ctx: Ctx): void {
  const s = ctx.s, now = ctx.now, config = s.config;
  if (s.unknown !== null) {
    for (const queued of s.queue) refuse(ctx, queued.request, 'STATE_UNKNOWN');
    s.queue = [];
  }
  // Deadline refusal (evaluated when stepped; see the pinned limit in the module comment).
  s.queue = s.queue.filter((queued) => { if (now < queued.request.deadlineMs) return true; refuse(ctx, queued.request, 'DEADLINE'); return false; });
  if (s.unknown === null) for (const scope of BUDGET_SCOPES) {
    const current = s.scopes[scope];
    if (current.kind === 'BLOCKED' && now >= current.notBeforeMs) {
      s.probeGenCounter += 1;
      s.scopes[scope] = { kind: 'PROBING', probeGen: s.probeGenCounter, probeGranted: false };
      ctx.effects.push(Object.freeze({ kind: 'PROBE_DUE', scope, probeGen: s.probeGenCounter }));
      ctx.dirty = true;
    }
  }
  // Requests that can never become eligible without an operator or protocol action are refused now.
  s.queue = s.queue.filter((queued) => {
    const { request } = queued;
    if (isMutation(request.operation) && s.admission === 'STOPPED' && !queued.viaHook) { refuse(ctx, request, 'ADMISSION_STOPPED'); return false; }
    if (request.operation === 'PROBE') {
      const scope = s.scopes[request.scope];
      if (scope.kind !== 'PROBING' || scope.probeGen !== request.probeGen || scope.probeGranted) { refuse(ctx, request, 'STALE_PROBE'); return false; }
    }
    return true;
  });
  const maxWindowMs = Math.max(...config.windows.map((window) => window.windowMs));
  s.charges = s.charges.filter((charge) => charge.slotHeld || charge.latestStartMs === null || charge.latestStartMs + maxWindowMs > now);
  s.charges.forEach((charge, index) => {
    if (charge.latestStartMs === null && !charge.uncertainAlerted && now >= charge.grantedAtMs + config.uncertainChargeAlertMs) {
      setCharge(ctx, index, { uncertainAlerted: true }); alert(ctx, 'UNCERTAIN_CHARGE_OUTSTANDING', charge.grantId);
    }
    const current = s.charges[index]!;
    if (current.slotHeld && current.latestStartMs !== null && !current.overdueAlerted && now >= current.latestStartMs + current.lifetimeMs + config.overdueGuardMs) {
      setCharge(ctx, index, { overdueAlerted: true }); alert(ctx, 'SLOT_OVERDUE', current.grantId); // never releases the slot
    }
  });
  if (s.unknown !== null) return;
  admit(ctx);
}

function admit(ctx: Ctx): void {
  const s = ctx.s, now = ctx.now, config = s.config;
  const fairness = config.windows.find((window) => window.windowMs === config.fairnessWindowMs)!;
  const windowsOk = (): boolean => config.windows.every((window) => active(s, now, window.windowMs) + 1 <= window.maxStarts);
  const used = (cls: PriorityClass): number => active(s, now, config.fairnessWindowMs, cls);
  const concurrencyOk = (cls: PriorityClass): boolean => {
    const held = s.charges.filter((charge) => charge.slotHeld);
    return held.length < config.concurrency && (cls === 'P0' || held.filter((charge) => charge.cls !== 'P0').length < config.concurrency - config.p0ReservedSlots);
  };
  const firstEligible = (cls: PriorityClass): QueuedRequest | undefined => s.queue.find((queued) => queued.request.cls === cls && eligible(s, queued));
  const grant = (queued: QueuedRequest): void => {
    const { request } = queued;
    s.queue = s.queue.filter((entry) => entry !== queued);
    s.charges.push({
      grantId: request.grantId, requestId: request.requestId, clientInstanceId: request.clientInstanceId, sessionId: request.sessionId, epoch: s.epoch,
      cls: request.cls, operation: request.operation, scope: request.scope, viaHook: queued.viaHook, probeGen: request.probeGen ?? null,
      lifetimeMs: request.lifetimeMs, grantedAtMs: now, latestStartMs: null, started: false, slotHeld: true,
      delivery: 'PENDING_PERSIST', persistRevision: -1, uncertainAlerted: false, overdueAlerted: false, seen: [],
    });
    if (request.operation === 'PROBE') { const scope = s.scopes[request.scope]; if (scope.kind === 'PROBING') s.scopes[request.scope] = { ...scope, probeGranted: true }; }
    ctx.dirty = true;
  };
  // Phase A: classes with eligible waiting work below their minimum, in priority order, one grant per pass.
  for (let progressed = true; progressed;) {
    progressed = false;
    for (const cls of PRIORITY_CLASSES) {
      const next = firstEligible(cls);
      if (next !== undefined && used(cls) < config.classShares[cls].minPerWindow && windowsOk() && concurrencyOk(cls)) { grant(next); progressed = true; }
    }
  }
  // Phase B: priority within ceilings, protecting the unmet minimums of other classes with eligible waiting work.
  for (const cls of PRIORITY_CLASSES) {
    for (;;) {
      const next = firstEligible(cls);
      if (next === undefined || used(cls) >= config.classShares[cls].maxPerWindow || !concurrencyOk(cls) || !windowsOk()) break;
      const protect = PRIORITY_CLASSES.filter((other) => other !== cls && firstEligible(other) !== undefined)
        .reduce((sum, other) => sum + Math.max(0, config.classShares[other].minPerWindow - used(other)), 0);
      if (active(s, now, fairness.windowMs) + 1 + protect > fairness.maxStarts) break;
      grant(next);
    }
  }
}

