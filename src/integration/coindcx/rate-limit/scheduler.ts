export const SNAPSHOT_FORMAT = 'coindcx-rest-limiter-snapshot/1';
const time = z.number().int().nonnegative().refine(Number.isSafeInteger);
const snapshotSchema = z.object({
  format: z.literal(SNAPSHOT_FORMAT),
  revision: time, takenAtMs: time, epoch: z.string().regex(ID),
  admission: z.enum(['OPEN', 'STOPPED']),
  unknown: z.enum(['SNAPSHOT_UNREADABLE', 'CLOCK_REGRESSION', 'PERSISTENCE_FAILED', 'RETRY_AFTER_UNBOUNDED']).nullable(),
  scopes: z.object({ API_AUTH: z.enum(['CLEAR', 'BLOCKED', 'PROBING']), PUBLIC: z.enum(['CLEAR', 'BLOCKED', 'PROBING']) }).strict(),
  failuresInRow: time, probeGenCounter: time,
  blocks: z.array(z.object({ receivedAtMs: time, fullWaitMs: z.number().int().positive().refine(Number.isSafeInteger), form: z.string().max(32) }).strict()),
  charges: z.array(z.object({
    grantId: z.string().regex(ID), requestId: z.string().regex(ID), clientInstanceId: z.string().regex(ID), sessionId: z.string().regex(ID), epoch: z.string().regex(ID),
    cls: z.enum(PRIORITY_CLASSES), operation: z.enum(['READ', 'PROBE', 'CREATE', 'CANCEL']), scope: z.enum(BUDGET_SCOPES), viaHook: z.boolean(), probeGen: time.nullable(),
    lifetimeMs: z.number().int().positive().refine(Number.isSafeInteger), grantedAtMs: time, latestStartMs: time.nullable(), started: z.boolean(), slotHeld: z.boolean(),
  }).strict()),
}).strict();
export type LimiterSnapshot = z.infer<typeof snapshotSchema>;

function snapshotOf(s: Draft, now: number): LimiterSnapshot {
  return Object.freeze({
    format: SNAPSHOT_FORMAT, revision: s.revision, takenAtMs: now, epoch: s.epoch, admission: s.admission, unknown: s.unknown,
    scopes: { API_AUTH: s.scopes.API_AUTH.kind, PUBLIC: s.scopes.PUBLIC.kind },
    failuresInRow: s.failuresInRow, probeGenCounter: s.probeGenCounter, blocks: s.blocks.map((block) => ({ ...block })),
    charges: s.charges.map((charge) => ({
      grantId: charge.grantId, requestId: charge.requestId, clientInstanceId: charge.clientInstanceId, sessionId: charge.sessionId, epoch: charge.epoch,
      cls: charge.cls, operation: charge.operation, scope: charge.scope, viaHook: charge.viaHook, probeGen: charge.probeGen,
      lifetimeMs: charge.lifetimeMs, grantedAtMs: charge.grantedAtMs, latestStartMs: charge.latestStartMs, started: charge.started, slotHeld: charge.slotHeld,
    })),
  });
}

/** The durable snapshot of the current state (revision `state.revision`). Pure; used by the W2 durable store. */
export function snapshotLimiterState(state: LimiterState): LimiterSnapshot {
  return snapshotOf(draft(state), state.lastNowMs);
}

/** Trustworthy elapsed-time evidence (U-M2-11; default none): same boot session, boot-relative monotonic elapsed time. */
export type ElapsedEvidence = Readonly<{ kind: 'SAME_BOOT_ELAPSED'; elapsedSinceSnapshotMs: number }>;
export type RestoreResult =
  | Readonly<{ kind: 'RESTORED'; state: LimiterState; effects: readonly SchedulerEffect[] }>
  | Readonly<{ kind: 'UNREADABLE'; state: LimiterState; effects: readonly SchedulerEffect[] }>;

/**
 * Restore after a coordinator restart. `persisted` is the last durably committed snapshot, or undefined when the
 * state file is missing although a prior run is known. Anything unreadable gives admission STOPPED with the throttle
 * UNKNOWN and no grants (operator recovery is U-M2-5, not implemented in W1).
 * Old monotonic times are not comparable with this incarnation's clock, so without elapsed evidence every finite
 * latest-start becomes `nowMs` (a later start bound is conservative) and every block re-waits its full duration from `nowMs`.
 */
export function restoreLimiterState(config: RateLimiterConfig, persisted: unknown, nowMs: number, epoch: string, evidence: ElapsedEvidence | null): RestoreResult {
  if (!isTime(nowMs) || !isId(epoch)) throw new TypeError('restoreLimiterState: invalid nowMs or epoch');
  const parsed = snapshotSchema.safeParse(persisted);
  const consistent = parsed.success && parsed.data.epoch !== epoch
    && BUDGET_SCOPES.every((scope) => parsed.data.scopes[scope] === 'CLEAR' || parsed.data.blocks.length > 0)
    && parsed.data.blocks.every((block) => block.receivedAtMs <= parsed.data.takenAtMs)
    && parsed.data.charges.every((charge) => (charge.latestStartMs === null || charge.latestStartMs <= parsed.data.takenAtMs) && charge.grantedAtMs <= parsed.data.takenAtMs)
    && new Set(parsed.data.charges.map((charge) => charge.grantId)).size === parsed.data.charges.length;
  const elapsed = evidence !== null && evidence.kind === 'SAME_BOOT_ELAPSED' && isTime(evidence.elapsedSinceSnapshotMs) ? evidence.elapsedSinceSnapshotMs : null;
  if (!parsed.success || !consistent) {
    const base = createLimiterState(config, nowMs, epoch);
    const result = step({ ...base, admission: 'STOPPED', unknown: 'SNAPSHOT_UNREADABLE' }, nowMs, { type: 'ADVANCE' });
    return Object.freeze({ kind: 'UNREADABLE', state: result.state, effects: result.effects });
  }
  const snap = parsed.data;
  // Map an old-incarnation time to this incarnation: with evidence, exact elapsed; otherwise `nowMs` (conservative).
  const convert = (oldMs: number): number => (elapsed === null ? nowMs : Math.max(0, nowMs - ((snap.takenAtMs - oldMs) + elapsed)));
  const remainingWait = (block: BlockRecord): number => (elapsed === null ? block.fullWaitMs : Math.max(0, block.fullWaitMs - ((snap.takenAtMs - block.receivedAtMs) + elapsed)));
  const notBeforeMs = nowMs + Math.max(0, ...snap.blocks.map(remainingWait));
  const scopes = Object.fromEntries(BUDGET_SCOPES.map((scope) => [scope, snap.scopes[scope] === 'CLEAR' ? { kind: 'CLEAR' } : { kind: 'BLOCKED', notBeforeMs }])) as Record<BudgetScope, ScopeThrottle>;
  const state: LimiterState = {
    config, epoch, lastNowMs: nowMs, admission: snap.admission, unknown: snap.unknown, scopes,
    failuresInRow: snap.failuresInRow, probeGenCounter: snap.probeGenCounter,
    // Without evidence each block restarts its full wait from nowMs; with evidence its receipt time is converted exactly.
    blocks: snap.blocks.map((block) => ({ ...block, receivedAtMs: convert(block.receivedAtMs) })),
    charges: snap.charges.map((charge) => ({
      ...charge, grantedAtMs: convert(charge.grantedAtMs), latestStartMs: charge.latestStartMs === null ? null : convert(charge.latestStartMs),
      delivery: 'DELIVERED', persistRevision: snap.revision, uncertainAlerted: false, overdueAlerted: false, seen: charge.started ? ['STARTED'] : [],
    })),
    queue: [], sessions: {}, revision: snap.revision, committedRevision: snap.revision, hookToken: null,
  };
  // Force a fresh durable write under the new epoch before any grant.
  const ctx: Ctx = { s: draft(state), now: nowMs, effects: [], dirty: true };
  progress(ctx);
  const result = finish(ctx);
  return Object.freeze({ kind: 'RESTORED', state: result.state, effects: result.effects });
}
